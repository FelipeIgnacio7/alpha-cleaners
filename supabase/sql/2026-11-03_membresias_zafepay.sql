-- Ingresos por membresías cobradas en Zafepay (cuotas de suscripción). 03-11-2026.
-- Tabla nueva; no toca nada existente. Idempotente. Sin nombres ni correos de clientes: solo plan, monto y fechas.
-- SEGURIDAD PENDIENTE: política abierta temporal, igual que el resto de la app.
create table if not exists membresias_zafepay (
  id bigint generated by default as identity primary key,
  plan text not null,
  tipo text,                    -- 'Suscripción', etc. (columna "Tipo" de Zafepay)
  valor numeric not null,       -- valor de la cuota en CLP
  fecha_vencimiento date,
  fecha_pago date,              -- null mientras no se pague
  referencia text,              -- referencia del proveedor de pago (null en pagos manuales)
  estado text not null,         -- 'Pagado', 'Pendiente', 'Vencido', ...
  created_at timestamptz not null default now()
);
create index if not exists membresias_zafepay_pago_idx on membresias_zafepay (fecha_pago);
create index if not exists membresias_zafepay_estado_idx on membresias_zafepay (estado);

alter table membresias_zafepay enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'membresias_zafepay' and policyname = 'abierto_temporal') then
    create policy abierto_temporal on membresias_zafepay for all using (true) with check (true);
  end if;
end $$;
