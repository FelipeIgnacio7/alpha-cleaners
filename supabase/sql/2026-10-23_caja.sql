create table if not exists caja_servicios (
  id bigint generated by default as identity primary key,
  nombre text not null,
  detalle text,
  precio_moto numeric,
  precio_pequeno numeric,
  precio_mediano numeric,
  precio_grande numeric,
  precio_xl numeric,
  es_membresia boolean not null default false,
  activo boolean not null default true,
  orden int not null default 100,
  created_at timestamptz not null default now()
);

create table if not exists caja_descuentos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  porcentaje numeric not null check (porcentaje > 0 and porcentaje <= 100),
  solo_servicio text,          -- si aplica solo a un servicio (ej. 'Lavado full'); null = a todo el trabajo
  campana text,                -- etiqueta para medir campañas (ej. 'recontacto_40')
  vigente_hasta date,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists caja_trabajos (
  id uuid primary key default gen_random_uuid(),
  local_id int not null references locales(id),
  fecha date not null,
  hora time not null,
  patente text,                -- normalizada: mayúsculas, sin espacios ni guiones
  cliente text,
  telefono text,
  marca text,
  modelo text,
  tamano text check (tamano in ('moto', 'pequeno', 'mediano', 'grande', 'xl')),
  items jsonb not null default '[]'::jsonb,   -- [{servicio_id, nombre, precio}]
  subtotal numeric not null default 0,
  descuento_id bigint references caja_descuentos(id),
  descuento_nombre text,
  descuento_monto numeric not null default 0,
  total numeric not null default 0,
  campana text,
  notas text,
  anulado boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists caja_trabajos_local_fecha_idx on caja_trabajos (local_id, fecha);
create index if not exists caja_trabajos_patente_idx on caja_trabajos (patente);

create table if not exists caja_pagos (
  id uuid primary key default gen_random_uuid(),
  trabajo_id uuid not null references caja_trabajos(id) on delete cascade,
  local_id int not null references locales(id),
  fecha date not null,
  monto numeric not null check (monto > 0),
  medio text not null check (medio in ('efectivo', 'debito', 'credito', 'transferencia')),
  created_at timestamptz not null default now()
);
create index if not exists caja_pagos_local_fecha_idx on caja_pagos (local_id, fecha);
create index if not exists caja_pagos_trabajo_idx on caja_pagos (trabajo_id);

create table if not exists caja_cierres (
  id uuid primary key default gen_random_uuid(),
  local_id int not null references locales(id),
  fecha date not null,
  resumen jsonb not null,
  efectivo_contado numeric,
  notas text,
  created_at timestamptz not null default now(),
  unique (local_id, fecha)
);

alter table caja_servicios enable row level security;
alter table caja_descuentos enable row level security;
alter table caja_trabajos enable row level security;
alter table caja_pagos enable row level security;
alter table caja_cierres enable row level security;

do $$
declare t text;
begin
  foreach t in array array['caja_servicios', 'caja_descuentos', 'caja_trabajos', 'caja_pagos', 'caja_cierres'] loop
    if not exists (select 1 from pg_policies where tablename = t and policyname = 'abierto_temporal') then
      execute format('create policy abierto_temporal on %I for all using (true) with check (true)', t);
    end if;
  end loop;
end $$;

